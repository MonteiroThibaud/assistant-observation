const OPTIONAL = ['./img/relief-fin.bin.gz', './img/etoiles.bin.gz'];   // relief fin et grand catalogue d'étoiles : gardés s'ils sont présents, sans bloquer l'installation sinon

self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(async c => { await c.addAll(FILES); await Promise.allSettled(OPTIONAL.map(u => c.add(u))); }));
  self.skipWaiting();
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(k => Promise.all(k.filter(x => x !== CACHE).map(x => caches.delete(x)))));
  self.clients.claim();
});
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  // Autres sites (par exemple les fichiers d'éléments d'orbite du MPC) : jamais gardés ni servis depuis le cache, pour que la mise à jour donne toujours la version du jour
  if (url.origin !== self.location.origin) return;
  // Pages autres que l'application (par exemple /.well-known/assetlinks.json) : on laisse le réseau répondre
  if (req.mode === 'navigate') {
    const p = url.pathname;
    if (!(p.endsWith('/') || p.endsWith('/index.html'))) return;
  }
  e.respondWith(caches.open(CACHE).then(async cache => {
    const key = req.mode === 'navigate' ? './index.html' : req;
    const hit = await cache.match(key, {ignoreSearch: true});
    const net = fetch(req).then(res => {
      if (res && (res.ok || res.type === 'opaque')) cache.put(key, res.clone());
      return res;
    }).catch(() => hit || Response.error());
    return hit || net;
  }));
});
